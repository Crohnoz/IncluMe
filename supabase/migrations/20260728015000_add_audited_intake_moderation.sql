create view public.citizen_moderation_queue
with (security_invoker = true)
as
select
  id,
  public_reference,
  report_type,
  commune,
  place_name,
  exact_reference,
  latitude,
  longitude,
  observation,
  contact_email,
  status,
  created_at,
  updated_at,
  reviewed_at,
  moderator_notes
from public.citizen_reports
where status in ('pending','triaged','needs_clarification')
order by created_at asc;

create view public.municipal_moderation_queue
with (security_invoker = true)
as
select
  id,
  public_reference,
  institution,
  territory,
  contact_name,
  contact_role,
  institutional_email,
  phone,
  objective,
  problem_description,
  status,
  created_at,
  updated_at,
  internal_notes
from public.municipal_pilot_requests
where status not in ('closed','archived')
order by created_at asc;

revoke all on public.citizen_moderation_queue from anon, authenticated;
revoke all on public.municipal_moderation_queue from anon, authenticated;

