drop function if exists public.promote_citizen_report_to_parking(text,text,text,text,text);

create or replace function public.promote_citizen_report_to_parking(
  p_public_reference text,
  p_transfer_side text default 'unknown',
  p_step_free text default 'unknown',
  p_confidence_label text default 'community_reviewed',
  p_moderator_notes text default null,
  p_actor_label text default 'inclume_team'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  report public.citizen_reports%rowtype;
  parking_id uuid;
  clean_actor text := coalesce(nullif(trim(p_actor_label), ''), 'inclume_team');
begin
  if p_transfer_side not in ('unknown','right','left','both') then
    raise exception 'invalid transfer side';
  end if;
  if p_step_free not in ('unknown','yes','no') then
    raise exception 'invalid step free value';
  end if;
  if p_confidence_label not in ('community_reviewed','institutional','field_audit') then
    raise exception 'invalid confidence label';
  end if;

  select * into report
  from public.citizen_reports
  where public_reference = upper(trim(p_public_reference))
  for update;

  if not found then
    raise exception 'report not found';
  end if;
  if report.latitude is null or report.longitude is null then
    raise exception 'report requires coordinates before publication';
  end if;

  insert into public.parking_locations (
    name,
    location_reference,
    commune,
    latitude,
    longitude,
    transfer_side,
    step_free,
    notes,
    confidence_label,
    moderation_status,
    is_published,
    source_report_id
  ) values (
    report.place_name,
    report.exact_reference,
    report.commune,
    report.latitude,
    report.longitude,
    p_transfer_side,
    p_step_free,
    report.observation,
    p_confidence_label,
    'approved',
    true,
    report.id
  )
  on conflict (source_report_id)
  do update set
    name = excluded.name,
    location_reference = excluded.location_reference,
    commune = excluded.commune,
    latitude = excluded.latitude,
    longitude = excluded.longitude,
    transfer_side = excluded.transfer_side,
    step_free = excluded.step_free,
    notes = excluded.notes,
    confidence_label = excluded.confidence_label,
    moderation_status = 'approved',
    is_published = true,
    updated_at = now()
  returning id into parking_id;

  update public.citizen_reports
  set status = 'accepted',
      reviewed_at = now(),
      moderator_notes = p_moderator_notes
  where id = report.id;

  insert into public.intake_moderation_events (
    entity_type,
    entity_id,
    public_reference,
    action,
    previous_status,
    new_status,
    notes,
    actor_label
  ) values (
    'citizen_report',
    report.id,
    report.public_reference,
    'published_to_catalog',
    report.status,
    'accepted',
    p_moderator_notes,
    clean_actor
  );

  insert into public.intake_moderation_events (
    entity_type,
    entity_id,
    public_reference,
    action,
    previous_status,
    new_status,
    notes,
    actor_label
  ) values (
    'parking_location',
    parking_id,
    report.public_reference,
    'catalog_record_approved',
    null,
    'approved',
    p_moderator_notes,
    clean_actor
  );

  return parking_id;
end;
$$;

