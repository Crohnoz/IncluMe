create table public.intake_moderation_events (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('citizen_report','municipal_request','parking_location')),
  entity_id uuid not null,
  public_reference text,
  action text not null check (char_length(action) between 2 and 80),
  previous_status text,
  new_status text,
  notes text check (notes is null or char_length(notes) <= 2000),
  actor_label text not null default 'inclume_team' check (char_length(actor_label) between 2 and 120),
  created_at timestamptz not null default now()
);

create index intake_moderation_events_entity_idx
  on public.intake_moderation_events (entity_type, entity_id, created_at desc);
create index intake_moderation_events_reference_idx
  on public.intake_moderation_events (public_reference, created_at desc);

alter table public.intake_moderation_events enable row level security;
revoke all on table public.intake_moderation_events from anon, authenticated;

create or replace function public.moderate_citizen_report(
  p_public_reference text,
  p_new_status text,
  p_notes text default null,
  p_actor_label text default 'inclume_team'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  report public.citizen_reports%rowtype;
  clean_reference text := upper(trim(p_public_reference));
  clean_actor text := coalesce(nullif(trim(p_actor_label), ''), 'inclume_team');
begin
  if p_new_status not in ('pending','triaged','needs_clarification','rejected','archived') then
    raise exception 'invalid citizen moderation status';
  end if;

  select * into report
  from public.citizen_reports
  where public_reference = clean_reference
  for update;

  if not found then
    raise exception 'citizen report not found';
  end if;

  update public.citizen_reports
  set status = p_new_status,
      reviewed_at = case when p_new_status = 'pending' then null else now() end,
      moderator_notes = p_notes
  where id = report.id;

  insert into public.intake_moderation_events (
    entity_type,
    entity_id,
    public_reference,
    action,
    previous_status,
    new_status,
    notes,
    actor_label
  ) values (
    'citizen_report',
    report.id,
    report.public_reference,
    'status_changed',
    report.status,
    p_new_status,
    p_notes,
    clean_actor
  );

  return report.id;
end;
$$;

